  function lsGet(k) { try { return localStorage.getItem(k); } catch(e) { return null; } }
  function lsSet(k, v) { try { localStorage.setItem(k, v); } catch(e) {} }

  var currentLang = lsGet('md-lang') || 'sr';

  function applyLang(lang) {
    currentLang = lang;
    lsSet('md-lang', lang);
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var val = translations[lang] && translations[lang][key];
      if (val) el.textContent = val;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      var val = translations[lang] && translations[lang][key];
      if (val) el.placeholder = val;
    });

    document.querySelectorAll('[data-i18n-label]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-label');
      var val = translations[lang] && translations[lang][key];
      if (val) el.textContent = val;
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-alt');
      var val = translations[lang] && translations[lang][key];
      if (val) el.alt = val;
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      var val = translations[lang] && translations[lang][key];
      if (val) el.innerHTML = val;
    });

    document.querySelectorAll('[data-i18n-content]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-content');
      var val = translations[lang] && translations[lang][key];
      if (val) el.setAttribute('content', val);
    });

    document.querySelectorAll('.lang-toggle-btn').forEach(function (btn) {
      btn.querySelector('[data-lang-sr]').style.fontWeight = lang === 'sr' ? '700' : '400';
      btn.querySelector('[data-lang-en]').style.fontWeight = lang === 'en' ? '700' : '400';
    });
  }

  function initI18n() {
    document.querySelectorAll('.lang-toggle-btn').forEach(function (btn) {
      btn.addEventListener('click', function (e) {
        var sr = e.target.closest('[data-lang-sr]');
        var en = e.target.closest('[data-lang-en]');
        if (sr) applyLang('sr');
        else if (en) applyLang('en');
      });
    });
    applyLang(currentLang);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n);
  } else {
    initI18n();
  }

  window.mdI18n = { apply: applyLang };
